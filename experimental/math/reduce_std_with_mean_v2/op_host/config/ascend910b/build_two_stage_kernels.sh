# ----------------------------------------------------------------------------
# Compile the two-stage kernel binaries (ReduceStdWithMeanV2Partial /
# ReduceStdWithMeanV2Merge) for Ascend910B.
#
# The repo's standard kernel-compile flow is per module op type only, so the
# extra op types of this module are compiled here directly with asc_opc, using
# the self binary configs (op_host/config/ascend910b/*_binary.json) and the
# per-op-type dynamic drivers generated by the impl-gen (the mirror target in
# the module CMakeLists provides the kernel sources under build/tbe/ascendc/).
#
# Usage: bash build_two_stage_kernels.sh <repo-top-dir>
# ----------------------------------------------------------------------------
set -e

TOPDIR=$(readlink -f "$1")
BUILD=$TOPDIR/build
SCRIPTS=$TOPDIR/scripts/kernel/binary_script
BIN_OUT=$BUILD/binary/ascend910b/bin
CFG_OUT=$BIN_OUT/config/ascend910b
SOC=Ascend910B1
SOC_LOWER=ascend910b
CFG_DIR=$(dirname "$(readlink -f "$0")")
WORK_DIR=$BUILD/tbe/two_stage_kernel_cfg   # clean temp dir per run

mkdir -p "$CFG_OUT" "$WORK_DIR"

compile_op() {
  local op_type="$1"     # PascalCase op type
  local func="$2"        # snake_case kernel entry
  local cfg="$3"         # self binary config json
  local bins="$4"        # number of bins in the config
  local bin_dir="$BIN_OUT/$SOC_LOWER/$func"
  local py="$BUILD/tbe/dynamic/$func.py"
  local base="$WORK_DIR/$func"

  if [ ! -f "$py" ]; then
    echo "[two-stage] skip $op_type: dynamic driver $py not generated yet"
    return 0
  fi
  rm -f "$base"* "$CFG_OUT/$func.json"
  cp "$cfg" "$base.json"
  mkdir -p "$bin_dir"
  python3 "$SCRIPTS/gen_opc_json_with_impl_mode.py" "$base.json" "${base}_high_performance.json" high_performance
  python3 "$SCRIPTS/gen_opc_json_with_threadnum.py" "${base}_high_performance.json" "$bins"
  for i in $(seq 0 $((bins - 1))); do
    param="${base}_high_performance.json_$i"
    echo "[two-stage] asc_opc $op_type bin $i ($func)"
    asc_opc "$py" --main_func="$func" --input_param="$param" \
        --soc_version=$SOC --output="$bin_dir" \
        --impl_mode=high_performance,optional --simplified_key_mode=0 --op_mode=dynamic
    # bin_dir needs a trailing slash: gen_output_json joins it with the bin name
    python3 "$SCRIPTS/gen_output_json.py" "$param" "$bin_dir/" "$CFG_OUT/$func.json"
  done
  echo "[two-stage] $op_type kernels compiled to $bin_dir"
}

compile_op ReduceStdWithMeanV2Partial reduce_std_with_mean_v2_partial \
    "$CFG_DIR/reduce_std_with_mean_v2_partial_binary.json" 3
# Merge always emits float32 (the L2 Casts to the original dtype), so one
# fp32 bin covers all input dtypes.
compile_op ReduceStdWithMeanV2Merge reduce_std_with_mean_v2_merge \
    "$CFG_DIR/reduce_std_with_mean_v2_merge_binary.json" 1

# Regenerate binary_info_config.json so it covers all kernels (including the
# two-stage bins); harmless if the repo's own scan runs before or after this one.
python3 "$SCRIPTS/gen_binary_info_config.py" "$BIN_OUT" "$SOC_LOWER" || true

echo "[two-stage] two-stage kernel compile done"
