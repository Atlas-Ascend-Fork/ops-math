uint32_t GetDataTypeSize(DataType dt)
{
    uint32_t dilation = 1;
    uint32_t twoByte = 2;
    uint32_t fourByte = 4;
    uint32_t eightByte = 8;

    if (dt == ge::DT_FLOAT) {
        dilation = fourByte;
    } else if (dt == ge::DT_FLOAT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_BF16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_UINT16) {
        dilation = twoByte;
    } else if (dt == ge::DT_INT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_UINT32) {
        dilation = fourByte;
    } else if (dt == ge::DT_INT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_UINT64) {
        dilation = eightByte;
    } else if (dt == ge::DT_INT8) {
        dilation = 1;
    }
    return dilation;
}

int32_t GenOnesData(vector<int64_t> shapes, Tensor& input_tensor, TensorDesc& input_tensor_desc, DataType data_type,
                    int value)
{
    input_tensor_desc.SetRealDimCnt(shapes.size());
    size_t size = 1;
    for (uint32_t i = 0; i < shapes.size(); i++) {
        size *= shapes[i];
    }
    uint64_t data_len = size * GetDataTypeSize(data_type);
    uint8_t* pData = new (std::nothrow) uint8_t[data_len];
    if (pData == nullptr) {
        return FAILED;
    }
    FILE* fp = fopen("./test_input.bin", "rb");
    if (fp != nullptr) {
        size_t read = fread(pData, 1, data_len, fp);
        fclose(fp);
        if (read != data_len) {
            printf("[WARN] test_input.bin: read %zu bytes, expected %zu\n", read, static_cast<size_t>(data_len));
        }
    } else {
        memset(pData, 0, data_len);
        printf("[WARN] test_input.bin not found, using zeros\n");
    }
    input_tensor = Tensor(input_tensor_desc, pData, data_len);
    delete[] pData;
    pData = nullptr;
    return SUCCESS;
}

int32_t WriteDataToFile(string bin_file, uint64_t data_size, uint8_t* inputData)
{
    if (data_size > 0 && inputData == nullptr) {
        printf("%s - ERROR - [XIR]: Write file %s failed, input data buffer is null while data size is %zu\n",
               GetTime().c_str(), bin_file.c_str(), static_cast<size_t>(data_size));
        return FAILED;
    }
    FILE* fp = fopen(bin_file.c_str(), "w");
    if (fp == nullptr) {
        printf("%s - ERROR - [XIR]: Open file %s failed\n", GetTime().c_str(), bin_file.c_str());
        return FAILED;
    }
    size_t written = fwrite(inputData, sizeof(uint8_t), data_size, fp);
    if (written != data_size) {
        printf("%s - ERROR - [XIR]: Write file %s failed, written %zu of %zu bytes\n", GetTime().c_str(),
               bin_file.c_str(), written, static_cast<size_t>(data_size));
        if (fclose(fp) != 0) {
            printf("%s - ERROR - [XIR]: Close file %s failed after short write (%s)\n", GetTime().c_str(),
                   bin_file.c_str(), strerror(errno));
        }
        return FAILED;
    }
    if (fclose(fp) != 0) {
        printf("%s - ERROR - [XIR]: Close file %s failed after writing %zu bytes (%s)\n", GetTime().c_str(),
               bin_file.c_str(), static_cast<size_t>(data_size), strerror(errno));
        return FAILED;
    }
    return SUCCESS;
}

