    if (ret != SUCCESS) {
        printf("%s - ERROR - [XIR]: Session add ir compute graph failed\n", GetTime().c_str());
        delete session;
        ge::GEFinalize();
        return FAILED;
    }

    printf("%s - INFO - [XIR]: Session add ir compute graph to ir session success\n", GetTime().c_str());
    printf("%s - INFO - [XIR]: dump graph to txt\n", GetTime().c_str());
    std::string file_path = "./dump";
    aclgrphDumpGraph(graph, file_path.c_str(), file_path.length());
    printf("%s - INFO - [XIR]: Start to run ir compute graph\n", GetTime().c_str());

    if (RunAndDumpGraph(session, graph_id, input, "tc_ge_irrun_test_static") != SUCCESS) {
        delete session;
        ge::GEFinalize();
        return FAILED;
    }

    // 动态 shape 图：desc 含 -1 未知维度，实际 shape 由输入数据推导
    printf("%s - INFO - [XIR]: Start to build dynamic shape graph (-1 unknown dims)\n", GetTime().c_str());
