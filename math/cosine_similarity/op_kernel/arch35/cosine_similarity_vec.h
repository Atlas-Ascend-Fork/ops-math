/*
 * 向量元素级路径（vector bound：小 reduce + 大非 reduce 维度）。
 *
 * 按「非 reduce 维度」切 tile；R 个 reduce 行一次载入 UB 并保留，打满 64 lane 向量单元，
 * 单遍读入 2N。计算采用与基线 SIMT 一致的逐元素归一化形式：
 *   n1 = max(sqrt(sum_r x1r^2), eps), n2 = max(sqrt(sum_r x2r^2), eps)
 * *   out = sum_r (x1r / n1) * (x2r / n2)
 * 避免 dot/(n1*n2) 在平方溢出（n1*n2=inf 且 dot=0）时 Ascend 向量 Div 对 0/inf 返回 nan 的问题，
 * 保证与 golden（torch 语义）一致。
 *
 * tile 映射（由 tiling 的 vecTileOuters/vecTileInner 决定）：
 *   - innerSize <= tileCols：TI = innerSize，G = tileCols/innerSize，按 outer 切 tile；
 *   - innerSize >  tileCols：G = 1，TI = tileCols，按 (outer, inner 段) 切 tile。
 * 输出 flat 索引 col0 = outer*innerSize + iStart，tile 内始终是连续 flat 区间。
 * 无跨核部分和 / SyncAll / workspace。
 */

