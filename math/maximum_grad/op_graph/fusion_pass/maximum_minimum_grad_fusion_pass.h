#ifndef OPS_MATH_MAXIMUM_GRAD_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_H_
#define OPS_MATH_MAXIMUM_GRAD_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_H_

#include "ge/fusion/pass/pattern_fusion_pass.h"

namespace ops {
using namespace ge;
using namespace fusion;

/**
 * @brief Maximum/Minimum grad fusion pass (5 -> 2), for Ascend950 series.
 * @details GreaterEqual/LessEqual + Select(SelectV2) ==> MaximumGrad/MinimumGrad.
 *          The Sum/Reshape ops after Select stay OUTSIDE the pattern boundary:
 *          they keep running as independent ops and take MaximumGrad/MinimumGrad
 *          outputs as inputs, so the broadcast reduction semantics of the
 *          original TF subgraph is preserved.
 *          One pass covers: MaximumGrad (GreaterEqual anchor) and MinimumGrad
 *          (LessEqual anchor), Select and SelectV2 variants, and all three
 *          output forms (dx-only / dy-only / both) generated by TF autodiff
 *          when var_list covers only part of the maximum/minimum inputs.
 */
class __attribute__((visibility("default"))) MaximumMinimumGradFusionPass : public PatternFusionPass {
protected:
    std::vector<PatternUniqPtr> Patterns() override;

    bool MeetRequirements(const std::unique_ptr<MatchResult>& match_result) override;

    std::unique_ptr<Graph> Replacement(const std::unique_ptr<MatchResult>& match_result) override;
};

} // namespace ops

#endif // OPS_MATH_MAXIMUM_GRAD_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_MAXIMUM_MINIMUM_GRAD_FUSION_PASS_H_
