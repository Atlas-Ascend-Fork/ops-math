// Output form of the gradient subgraph, mirrors TF math_grad.py
// _MaximumMinimumGrad skip_input_indices branches.
enum class GradForm { kDxOnly, kDyOnly, kBoth };

// Platform gate by NpuArch: Ascend950 与 Ascend350 上报的 NpuArch 同为 DAV_3510,
// 按 arch 判断可同时覆盖两档芯片且免疫 soc 字符串的型号后缀差异
// (参考 drop_out_v3_fusion_pass)。
static bool IsTargetPlatform()
{
    char npuArchVal[32] = {0};
    if (rtGetSocSpec("version", "NpuArch", npuArchVal, sizeof(npuArchVal)) != RT_ERROR_NONE) {
        OP_LOGW(kPassName.c_str(), "Get NpuArch from soc spec failed, skip pass.");
        return false;
    }
    const auto npuArch = static_cast<NpuArch>(std::strtol(npuArchVal, nullptr, 10));
    static const std::set<NpuArch> supportedArch = {NpuArch::DAV_3510};
    const bool isSupported = (supportedArch.count(npuArch) > 0);
    if (!isSupported) {
        OP_LOGI(kPassName.c_str(), "Platform NpuArch %u is not supported(DAV_3510), skip pass.",
                static_cast<uint32_t>(npuArch));
    }
    return isSupported;
}

// The cmp node must be generated by TF autodiff: its name scope contains
// "Maximum_grad" (GreaterEqual) or "Minimum_grad" (LessEqual) — the naming
// produced by tf.gradients() (TF1-style API). TF2 GradientTape instead names
// backward nodes "gradient_tape[_N]/<op>" without any per-op scope.
static bool HasNameScope(const std::string& nodeName, const std::string& scope)
{
    std::string rest = nodeName;
    const std::string delimiter = "/";
    size_t pos = rest.find(delimiter);
    while (pos != std::string::npos) {
        if (rest.substr(0UL, pos) == scope) {
            return true;
        }
        rest.erase(0UL, pos + delimiter.length());
        pos = rest.find(delimiter);
    }
    return rest == scope;
}

// TF2 GradientTape naming: accept any name segment starting with
// "gradient_tape" (covers gradient_tape, gradient_tape_1, ...). The fused op
// type is still decided by the captured cmp node type, and the structural /
// dtype / all-zero-zeros checks guard the semantic equivalence, so the tape
// scope is sufficient autodiff evidence.
static bool HasGradientTapeScope(const std::string& nodeName)
{
    std::string rest = nodeName;
    const std::string delimiter = "/";
    size_t pos = rest.find(delimiter);
    while (pos != std::string::npos) {
        if (rest.substr(0UL, pos).rfind("gradient_tape", 0) == 0) {
            return true;
        }
        rest.erase(0UL, pos + delimiter.length());
        pos = rest.find(delimiter);
    }
    return rest.rfind("gradient_tape", 0) == 0;
}

// Resolve the TensorDesc of a subgraph input's first matched input.
// Fallback: if the input desc's shape is empty, get it from the source data node's output desc instead.
static TensorDesc ResolveSubgraphInputTensorDesc(const SubgraphInput& subgraphInput)
{
    auto matchNode = subgraphInput.GetAllInputs().at(0);
    TensorDesc tensorDesc;
    matchNode.node.GetInputDesc(matchNode.index, tensorDesc);
    if (tensorDesc.GetShape().GetDims().empty()) {
        auto srcInfo = matchNode.node.GetInDataNodesAndPortIndexs(static_cast<int32_t>(matchNode.index));
        if (srcInfo.first != nullptr) {
            GNode srcNode = *srcInfo.first;
            srcNode.GetOutputDesc(srcInfo.second, tensorDesc);
        }
    }
    return tensorDesc;
}

static std::string GetNodeName(const GNode& node)
{
    AscendString name;
    if (node.GetName(name) != GRAPH_SUCCESS) {
        return "";
    }
    return std::string(name.GetString());
}

static bool IsSupportedDtype(DataType dtype)
{
    return dtype == DT_FLOAT16 || dtype == DT_FLOAT || dtype == DT_BF16 || dtype == DT_INT32;
}

// The zeros input producer must be a Const node whose value is all zero.
// Non-zero else-branch would break the equivalence of the fusion.
static bool IsAllZeroConstInput(const SubgraphInput& subgraphInput)
{
    auto boundaryIo = subgraphInput.GetAllInputs().at(0);
    auto producerInfo = boundaryIo.node.GetInDataNodesAndPortIndexs(static_cast<int32_t>(boundaryIo.index));
    if (producerInfo.first == nullptr) {
        OP_LOGD(kPassName.c_str(), "Zeros input has no producer node, skip.");
        return false;
    }
    GNode zerosNode = *producerInfo.first;
    AscendString nodeType;
    if (zerosNode.GetType(nodeType) != GRAPH_SUCCESS) {
        OP_LOGD(kPassName.c_str(), "Zeros input producer type is unknown, skip.");
        return false;
    }
    const std::string zerosType = nodeType.GetString();
    if (zerosType != kConstOpType && zerosType != kGeConstantOpType) {
        OP_LOGD(kPassName.c_str(), "Zeros input producer is not Const/Constant, skip.");
        return false;
    }
    Tensor valueTensor;
    if (zerosNode.GetAttr("value", valueTensor) != GRAPH_SUCCESS) {
        OP_LOGD(kPassName.c_str(), "Zeros Const has no value attr, skip.");
        return false;
    }
    const uint8_t* data = valueTensor.GetData();
    size_t size = valueTensor.GetSize();
    if (data == nullptr || size == 0UL) {
        OP_LOGD(kPassName.c_str(), "Zeros Const value is empty, skip.");
        return false;
    }
    for (size_t i = 0; i < size; ++i) {
        if (data[i] != 0) {
            OP_LOGD(kPassName.c_str(), "Zeros Const value is not all zero, skip.");
            return false;
        }
    }
    return true;
}

static std::vector<int64_t> GetDims(const Shape& shape)
{
    std::vector<int64_t> dims;
    for (size_t i = 0; i < shape.GetDimNum(); i++) {
        dims.push_back(shape.GetDim(i));
    }
    return dims;
}

// Right-aligned numpy-style broadcast of the given shapes; -1 is treated as a
// wildcard dim. Returns false when the shapes cannot be broadcast together.
static bool BroadcastDims(const std::vector<Shape>& shapes, std::vector<int64_t>& outDims)
{
    size_t maxRank = 0UL;
    for (const auto& shape : shapes) {
        maxRank = (shape.GetDimNum() > maxRank) ? shape.GetDimNum() : maxRank;
    }
    outDims.assign(maxRank, 1L);
    for (size_t i = 0UL; i < maxRank; i++) {
        for (const auto& shape : shapes) {
            const size_t rank = shape.GetDimNum();
            if (i + rank < maxRank) {
                continue; // missing leading dim broadcasts as 1
            }
            const int64_t dim = shape.GetDim(i + rank - maxRank);
            if (dim == -1L) {
                outDims[i] = -1L;
                continue;
            }
            if (dim != 1L) {
                if (outDims[i] != 1L && outDims[i] != dim) {
                    return false;
                }
                outDims[i] = dim;
            }
        }
    }
    return true;
}

// Whether the producer of node's input[inputIdx] has the given name.
static bool InputProducerHasName(const GNode& node, int32_t inputIdx, const std::string& producerName)
{
    if (producerName.empty()) {
        return false;
    }
    auto producerInfo = node.GetInDataNodesAndPortIndexs(inputIdx);
    if (producerInfo.first == nullptr) {
        return false;
    }
    return GetNodeName(*producerInfo.first) == producerName;
}

// Name of the outside producer node feeding subgraphInputs[idx].
static std::string GetBoundaryInputProducerName(const std::vector<SubgraphInput>& subgraphInputs, size_t idx)
{
    if (idx >= subgraphInputs.size()) {
        return "";
    }
    auto boundaryIo = subgraphInputs[idx].GetAllInputs().at(0);
    auto producerInfo = boundaryIo.node.GetInDataNodesAndPortIndexs(static_cast<int32_t>(boundaryIo.index));
    if (producerInfo.first == nullptr) {
        return "";
    }
    return GetNodeName(*producerInfo.first);
}

// Fetch the subgraph boundary inputs and validate the input count.
static bool GetSubgraphInputs(const std::unique_ptr<MatchResult>& matchResult,
                              std::vector<SubgraphInput>& subgraphInputs)
{
    matchResult->ToSubgraphBoundary()->GetAllInputs(subgraphInputs);
    if (subgraphInputs.size() != kPatternInputNum) {
        OP_LOGE(kPassName.c_str(), "Subgraph input num %zu != %zu.", subgraphInputs.size(), kPatternInputNum);
        return false;
    }
    return true;
}

// Collect the matched Select/SelectV2 nodes from the match result.
static std::vector<GNode> GetMatchedSelectNodes(const MatchResult& matchResult)
{
    std::vector<GNode> selectNodes;
    for (const auto& matchedNode : matchResult.GetMatchedNodes()) {
        AscendString nodeType;
        if (matchedNode.GetType(nodeType) != GRAPH_SUCCESS) {
            continue;
        }
        const std::string type = nodeType.GetString();
        if (type == kSelectOpType || type == kSelectV2OpType) {
            selectNodes.push_back(matchedNode);
        }
    }
    return selectNodes;
}

// Resolve the captured cmp node (capture index kCaptureIdxCmp) and its op type.
static bool GetCapturedCmp(const std::unique_ptr<MatchResult>& matchResult, NodeIo& cmpIo, std::string& cmpType)
{
    if (matchResult->GetCapturedTensor(kCaptureIdxCmp, cmpIo) != SUCCESS) {
        OP_LOGE(kPassName.c_str(), "Failed to get captured cmp tensor.");
        return false;
    }
    AscendString cmpTypeStr;
    if (cmpIo.node.GetType(cmpTypeStr) != GRAPH_SUCCESS) {
        OP_LOGE(kPassName.c_str(), "Failed to get cmp node type.");
        return false;
    }
    cmpType = cmpTypeStr.GetString();
    return true;
}

// Decide the output form from the matched selects:
//   2 selects -> both (grad_x=true, grad_y=true)
//   1 select  -> dx-only if its then-input (input 1) producer is dz (boundary input 0),
//                otherwise dy-only.
static bool ResolveGradForm(const MatchResult& matchResult, const std::vector<SubgraphInput>& subgraphInputs,
                            bool& gradX, bool& gradY)
{
    std::vector<GNode> selectNodes = GetMatchedSelectNodes(matchResult);
    if (selectNodes.size() == 2UL) {
        gradX = true;
        gradY = true;
        return true;
    }
    if (selectNodes.size() == 1UL) {
        const std::string dzProducerName = GetBoundaryInputProducerName(subgraphInputs, kInputIdxGrads);
        gradX = InputProducerHasName(selectNodes[0], 1, dzProducerName);
        gradY = !gradX;
        return true;
    }
    OP_LOGE(kPassName.c_str(), "Matched select node num %zu is unexpected.", selectNodes.size());
    return false;
}

// Build one pattern:
//   dz(0) --------------------+--------------------------> Select[ V2 ]_dx.t
//   x1(1) ->+-> GE/LE --+----+--> Select[ V2 ]_dx.cond
//   x2(2) ->+            +--------> Select[ V2 ]_dy.cond
//   zeros(3) -----------------------> Select[ V2 ]_dx.e, Select[ V2 ]_dy.t
//   form controls which Select(s) exist and the output list:
//     kBoth:  outputs = [Select_dx output, Select_dy output]
//     kDxOnly: outputs = [Select_dx output]
//     kDyOnly: outputs = [Select_dy output]
//   capture[0]: cmp output, used to decide MaximumGrad/MinimumGrad in hooks.
static PatternUniqPtr MakeGradPattern(const std::string& cmpOpType, const std::string& selectOpType,
                                      const std::vector<std::string>& selectInputNames,
                                      const std::string& selectOutputName, GradForm form)
{
    auto graphBuilder = es::EsGraphBuilder(kPassName.c_str());
    auto dz = graphBuilder.CreateInput(static_cast<int64_t>(kInputIdxGrads), "dz");
    auto x1 = graphBuilder.CreateInput(static_cast<int64_t>(kInputIdxX1), "x1");
    auto x2 = graphBuilder.CreateInput(static_cast<int64_t>(kInputIdxX2), "x2");
    auto zeros = graphBuilder.CreateInput(static_cast<int64_t>(kInputIdxZeros), "zeros");
    auto* graph = graphBuilder.GetCGraphBuilder()->GetGraph();

    auto cmpNode = es::CompliantNodeBuilder(graph)
                       .OpType(cmpOpType.c_str())
                       .Name("cmp")
                       .IrDefInputs({{"x1", es::CompliantNodeBuilder::kEsIrInputRequired, ""},
                                     {"x2", es::CompliantNodeBuilder::kEsIrInputRequired, ""}})
                       .IrDefOutputs({{"y", es::CompliantNodeBuilder::kEsIrOutputRequired, ""}})
                       .Build();

    const auto buildSelect = [graph, &selectOpType, &selectInputNames, &selectOutputName](const std::string& name) {
        return es::CompliantNodeBuilder(graph)
            .OpType(selectOpType.c_str())
            .Name(name.c_str())
            .IrDefInputs({{selectInputNames[0], es::CompliantNodeBuilder::kEsIrInputRequired, ""},
                          {selectInputNames[1], es::CompliantNodeBuilder::kEsIrInputRequired, ""},
                          {selectInputNames[2], es::CompliantNodeBuilder::kEsIrInputRequired, ""}})
            .IrDefOutputs({{selectOutputName, es::CompliantNodeBuilder::kEsIrOutputRequired, ""}})
            .Build();
    };

    GNode selectDxNode;
    GNode selectDyNode;
    if (form != GradForm::kDyOnly) {
        selectDxNode = buildSelect("select_dx");
    }
    if (form != GradForm::kDxOnly) {
        selectDyNode = buildSelect("select_dy");
    }

    if (es::AddEdgeAndUpdatePeerDesc(*graph, *x1.GetProducer(), x1.GetProducerOutIndex(), cmpNode, 0) !=
            GRAPH_SUCCESS ||
        es::AddEdgeAndUpdatePeerDesc(*graph, *x2.GetProducer(), x2.GetProducerOutIndex(), cmpNode, 1) !=
            GRAPH_SUCCESS) {
        OP_LOGE(kPassName.c_str(), "Failed to add cmp edge in pattern for %s.", cmpOpType.c_str());
        return nullptr;
    }
    if (form != GradForm::kDyOnly) {
        if (es::AddEdgeAndUpdatePeerDesc(*graph, cmpNode, 0, selectDxNode, 0) != GRAPH_SUCCESS ||
            es::AddEdgeAndUpdatePeerDesc(*graph, *dz.GetProducer(), dz.GetProducerOutIndex(), selectDxNode, 1) !=
                GRAPH_SUCCESS ||
            es::AddEdgeAndUpdatePeerDesc(*graph, *zeros.GetProducer(), zeros.GetProducerOutIndex(), selectDxNode, 2) !=
                GRAPH_SUCCESS) {
            OP_LOGE(kPassName.c_str(), "Failed to add select_dx edge in pattern.");
            return nullptr;
        }
    }
    if (form != GradForm::kDxOnly) {
        if (es::AddEdgeAndUpdatePeerDesc(*graph, cmpNode, 0, selectDyNode, 0) != GRAPH_SUCCESS ||
            es::AddEdgeAndUpdatePeerDesc(*graph, *zeros.GetProducer(), zeros.GetProducerOutIndex(), selectDyNode, 1) !=
                GRAPH_SUCCESS ||
            es::AddEdgeAndUpdatePeerDesc(*graph, *dz.GetProducer(), dz.GetProducerOutIndex(), selectDyNode, 2) !=
                GRAPH_SUCCESS) {
            OP_LOGE(kPassName.c_str(), "Failed to add select_dy edge in pattern.");
            return nullptr;
        }
    }

    auto cmpOut = graphBuilder.GetCGraphBuilder()->GetTensorHolderFromNode(cmpNode, 0);
    if (cmpOut == nullptr) {
        OP_LOGE(kPassName.c_str(), "Failed to get cmp output holder for %s pattern.", cmpOpType.c_str());
        return nullptr;
    }
    std::vector<es::EsTensorHolder> outputs;
    if (form != GradForm::kDyOnly) {
        auto y1 = graphBuilder.GetCGraphBuilder()->GetTensorHolderFromNode(selectDxNode, 0);
        if (y1 == nullptr) {
            OP_LOGE(kPassName.c_str(), "Failed to get select_dx output holder for %s pattern.", cmpOpType.c_str());
            return nullptr;
        }
        outputs.emplace_back(es::EsTensorHolder(y1));
    }
    if (form != GradForm::kDxOnly) {
        auto y2 = graphBuilder.GetCGraphBuilder()->GetTensorHolderFromNode(selectDyNode, 0);
        if (y2 == nullptr) {
            OP_LOGE(kPassName.c_str(), "Failed to get select_dy output holder for %s pattern.", cmpOpType.c_str());
            return nullptr;
        }
        outputs.emplace_back(es::EsTensorHolder(y2));
    }

    auto builtGraph = graphBuilder.BuildAndReset(outputs);
    if (builtGraph == nullptr) {
        OP_LOGE(kPassName.c_str(), "Failed to build pattern graph for %s.", cmpOpType.c_str());
        return nullptr;
    }
    auto pattern = std::make_unique<Pattern>(std::move(*builtGraph));
    pattern->CaptureTensor({cmpOut->GetProducer(), 0});
    return pattern;
}

std::vector<PatternUniqPtr> MaximumMinimumGradFusionPass::Patterns()
{
    OP_LOGD(kPassName.c_str(), "Enter Patterns for MaximumMinimumGradFusionPass.");
    std::vector<PatternUniqPtr> patternGraphs;
    if (!IsSupportedRuntimeVersion()) {
        OP_LOGD(kPassName.c_str(), "GE runtime version is below 9.0.0, skip pass.");
        return patternGraphs;
    }
    const std::vector<std::string> selectIrInputs = {"condition", "x1", "x2"};
    const std::string selectIrOutput = "y";
    // SelectV2 has the same IR port names as Select (condition/x1/x2 -> y, see
    // aic-ascend950-ops-info-math.json). The previous TF-flavoured names
    // (then/else -> result) never matched a real GE graph, so every SelectV2
    // pattern was dead.
    const std::vector<std::string> selectV2IrInputs = {"condition", "x1", "x2"};
    const std::string selectV2IrOutput = "y";
    const std::vector<std::pair<std::string, std::pair<std::vector<std::string>, std::string>>> selectVariants = {
        {"Select", {selectIrInputs, selectIrOutput}},
        {"SelectV2", {selectV2IrInputs, selectV2IrOutput}},
    };
    const std::vector<std::string> cmpOpTypes = {kCmpGreaterEqual, kCmpLessEqual};
    const std::vector<GradForm> gradForms = {GradForm::kBoth, GradForm::kDxOnly, GradForm::kDyOnly};
    for (const std::string& cmpOpType : cmpOpTypes) {
        for (const auto& selectVariant : selectVariants) {
            for (const GradForm form : gradForms) {
                auto pattern = MakeGradPattern(cmpOpType, selectVariant.first, selectVariant.second.first,
                                               selectVariant.second.second, form);
                if (pattern != nullptr) {
                    patternGraphs.emplace_back(std::move(pattern));
                }
            }
        }
    }
    OP_LOGD(kPassName.c_str(), "MaximumMinimumGradFusionPass created %zu patterns.", patternGraphs.size());
    return patternGraphs;
}

bool MaximumMinimumGradFusionPass::MeetRequirements(const std::unique_ptr<MatchResult>& matchResult)
{
    OP_LOGD(kPassName.c_str(), "Enter MeetRequirements for MaximumMinimumGradFusionPass.");
    if (!IsSupportedRuntimeVersion()) {
        OP_LOGD(kPassName.c_str(), "GE runtime version is below 9.0.0, skip pass.");
        return false;
    }
    if (!IsTargetPlatform()) {
        OP_LOGD(kPassName.c_str(), "Platform check failed, skip fusion.");
        return false;
    }

    NodeIo cmpIo;
    std::string cmpType;
    if (!GetCapturedCmp(matchResult, cmpIo, cmpType)) {
        return false;
    }
    std::string gradScope;
    if (cmpType == kCmpGreaterEqual) {
        gradScope = kScopeMaximumGrad;
    } else if (cmpType == kCmpLessEqual) {
        gradScope = kScopeMinimumGrad;
    } else {
        OP_LOGD(kPassName.c_str(), "Captured node type %s is unexpected, skip.", cmpType.c_str());
        return false;
    }

    const std::string cmpName = GetNodeName(cmpIo.node);
    if (cmpName.empty()) {
        OP_LOGE(kPassName.c_str(), "Failed to get cmp node name.");
        return false;
    }
    if (!HasNameScope(cmpName, gradScope) && !HasGradientTapeScope(cmpName)) {
        OP_LOGD(kPassName.c_str(), "Node %s is not in %s scope (nor gradient_tape), skip.", cmpName.c_str(),
                gradScope.c_str());
        return false;
    }

    std::vector<SubgraphInput> subgraphInputs;
    if (!GetSubgraphInputs(matchResult, subgraphInputs)) {
        return false;
    }

    TensorDesc gradsDesc = ResolveSubgraphInputTensorDesc(subgraphInputs[kInputIdxGrads]);
    if (!IsSupportedDtype(gradsDesc.GetDataType())) {
        OP_LOGD(kPassName.c_str(), "Grads dtype %d is not supported, skip.", static_cast<int>(gradsDesc.GetDataType()));
        return false;
    }

    // 算子规格要求 grads/x1/x2 三输入 dtype 一致;
    TensorDesc x1Desc = ResolveSubgraphInputTensorDesc(subgraphInputs[kInputIdxX1]);
    TensorDesc x2Desc = ResolveSubgraphInputTensorDesc(subgraphInputs[kInputIdxX2]);
    if (x1Desc.GetDataType() != gradsDesc.GetDataType() || x2Desc.GetDataType() != gradsDesc.GetDataType()) {
        OP_LOGD(kPassName.c_str(), "Input dtypes mismatch (grads=%d, x1=%d, x2=%d), skip.",
                static_cast<int>(gradsDesc.GetDataType()), static_cast<int>(x1Desc.GetDataType()),
                static_cast<int>(x2Desc.GetDataType()));
        return false;
    }

    if (!IsAllZeroConstInput(subgraphInputs[kInputIdxZeros])) {
        return false;
    }

    OP_LOGD(kPassName.c_str(), "MeetRequirements returns true, node %s.", cmpName.c_str());
    return true;
}

std::unique_ptr<Graph> MaximumMinimumGradFusionPass::Replacement(const std::unique_ptr<MatchResult>& matchResult)
{
    OP_LOGD(kPassName.c_str(), "Enter Replacement for MaximumMinimumGradFusionPass.");

    std::vector<SubgraphInput> subgraphInputs;
    if (!GetSubgraphInputs(matchResult, subgraphInputs)) {
        return nullptr;
    }

    bool gradX = false;
    bool gradY = false;
    if (!ResolveGradForm(*matchResult, subgraphInputs, gradX, gradY)) {
        return nullptr;
    }

    std::vector<Shape> inputShapes;
    std::vector<DataType> inputDtypes;
    std::vector<Format> inputFormats;
    for (const auto& subgraphInput : subgraphInputs) {
        TensorDesc tensorDesc = ResolveSubgraphInputTensorDesc(subgraphInput);
        inputShapes.emplace_back(tensorDesc.GetShape());
        inputDtypes.emplace_back(tensorDesc.GetDataType());
        inputFormats.emplace_back(tensorDesc.GetFormat());
    }

    NodeIo cmpIo;
    std::string cmpType;
    if (!GetCapturedCmp(matchResult, cmpIo, cmpType)) {
        return nullptr;
    }
    const std::string fusedOpType = (cmpType == kCmpGreaterEqual) ? kOpMaximumGrad : kOpMinimumGrad;

    auto replaceBuilder = es::EsGraphBuilder("replacement");
    // Replacement input index i maps to pattern boundary input index i.
    auto rGrads = replaceBuilder.CreateInput(static_cast<int64_t>(kInputIdxGrads), "grads", inputDtypes[0],
                                             inputFormats[0], GetDims(inputShapes[0]));
    auto rX1 = replaceBuilder.CreateInput(static_cast<int64_t>(kInputIdxX1), "x1", inputDtypes[1], inputFormats[1],
                                          GetDims(inputShapes[1]));
    auto rX2 = replaceBuilder.CreateInput(static_cast<int64_t>(kInputIdxX2), "x2", inputDtypes[2], inputFormats[2],
                                          GetDims(inputShapes[2]));
    // Boundary input 3 (zeros) is folded into the fused op (the mask zero
    // branch); the input slot is kept only for boundary index mapping.
    auto rZeros = replaceBuilder.CreateInput(static_cast<int64_t>(kInputIdxZeros), "zeros", inputDtypes[3],
                                             inputFormats[3], GetDims(inputShapes[3]));
    (void)rZeros;

    auto* graph = replaceBuilder.GetCGraphBuilder()->GetGraph();
    auto fusedNode = es::CompliantNodeBuilder(graph)
                         .OpType(fusedOpType.c_str())
                         .Name(fusedOpType == kOpMaximumGrad ? "maximum_grad" : "minimum_grad")
                         .IrDefInputs({{"grads", es::CompliantNodeBuilder::kEsIrInputRequired, ""},
                                       {"x1", es::CompliantNodeBuilder::kEsIrInputRequired, ""},
                                       {"x2", es::CompliantNodeBuilder::kEsIrInputRequired, ""}})
                         .IrDefOutputs({{"y1", es::CompliantNodeBuilder::kEsIrOutputRequired, ""},
                                        {"y2", es::CompliantNodeBuilder::kEsIrOutputRequired, ""}})
                         .IrDefAttrs(
                             {{"grad_x", es::CompliantNodeBuilder::kEsAttrRequired, "Bool", es::CreateFrom(gradX)},
                              {"grad_y", es::CompliantNodeBuilder::kEsAttrRequired, "Bool", es::CreateFrom(gradY)}})
                         .Build();

    if (es::AddEdgeAndUpdatePeerDesc(*graph, *rGrads.GetProducer(), rGrads.GetProducerOutIndex(), fusedNode, 0) !=
            GRAPH_SUCCESS ||
        es::AddEdgeAndUpdatePeerDesc(*graph, *rX1.GetProducer(), rX1.GetProducerOutIndex(), fusedNode, 1) !=
            GRAPH_SUCCESS ||
        es::AddEdgeAndUpdatePeerDesc(*graph, *rX2.GetProducer(), rX2.GetProducerOutIndex(), fusedNode, 2) !=
            GRAPH_SUCCESS) {
        OP_LOGE(kPassName.c_str(), "Failed to add edge for %s inputs.", fusedOpType.c_str());
        return nullptr;
    }

    auto y1 = replaceBuilder.GetCGraphBuilder()->GetTensorHolderFromNode(fusedNode, 0);
    auto y2 = replaceBuilder.GetCGraphBuilder()->GetTensorHolderFromNode(fusedNode, 1);
    if (y1 == nullptr || y2 == nullptr) {
        OP_LOGE(kPassName.c_str(), "Failed to get output holders for %s.", fusedOpType.c_str());
        return nullptr;
    }
    // The unused output of a single-form fusion stays unconnected, matching
    // the op tiling outputCount mode (1=y1 only, 2=y2 only, 3=both).
    std::vector<es::EsTensorHolder> outputs;
    if (gradX) {
        outputs.emplace_back(es::EsTensorHolder(y1));
    }
    if (gradY) {
        outputs.emplace_back(es::EsTensorHolder(y2));
    }
    auto replaceGraph = replaceBuilder.BuildAndReset(outputs);
    if (replaceGraph == nullptr) {
        OP_LOGE(kPassName.c_str(), "Failed to build replacement graph for %s.", fusedOpType.c_str());
        return nullptr;
    }

    if (GeUtils::InferShape(*replaceGraph, inputShapes) != SUCCESS) {
        OP_LOGE(kPassName.c_str(), "InferShape for replacement failed.");
        return nullptr;
    }

    // The fused op has broadcast output semantics (y1 == y2 == broadcast(grads,
    // x1, x2)), see maximum_grad_infershape.cpp / minimum_grad_infershape.cpp.
    // The ES builder / GeUtils::InferShape only propagate input-side descs, so
    // the output descs must be set explicitly AFTER InferShape (for connected
    // AND dangling outputs), otherwise tiling validation fails on broadcast /
    // single-form cases.
    std::vector<int64_t> bcastDims;
    const std::vector<Shape> opInputShapes = {inputShapes[kInputIdxGrads], inputShapes[kInputIdxX1],
                                              inputShapes[kInputIdxX2]};
    if (!BroadcastDims(opInputShapes, bcastDims)) {
        OP_LOGE(kPassName.c_str(), "Inputs of %s cannot be broadcast together.", fusedOpType.c_str());
        return nullptr;
    }
    Shape outShape(bcastDims);
    for (size_t outIdx = 0UL; outIdx < 2UL; outIdx++) {
        TensorDesc outDesc;
        outDesc.SetDataType(inputDtypes[kInputIdxGrads]);
        outDesc.SetFormat(inputFormats[kInputIdxGrads]);
        outDesc.SetShape(outShape);
        outDesc.SetOriginShape(outShape);
        outDesc.SetOriginFormat(inputFormats[kInputIdxGrads]);
        if (fusedNode.UpdateOutputDesc(static_cast<int32_t>(outIdx), outDesc) != GRAPH_SUCCESS) {
            OP_LOGE(kPassName.c_str(), "Failed to update output desc %zu for %s.", outIdx, fusedOpType.c_str());
            return nullptr;
        }
    }

    OP_LOGI(kPassName.c_str(), "MaximumMinimumGradFusionPass fused to %s successfully, grad_x=%d, grad_y=%d.",
            fusedOpType.c_str(), static_cast<int>(gradX), static_cast<int>(gradY));
    return replaceGraph;
}

