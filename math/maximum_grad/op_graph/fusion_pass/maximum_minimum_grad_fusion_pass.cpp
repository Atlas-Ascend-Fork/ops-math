/*!
 * \file maximum_minimum_grad_fusion_pass.cpp
 * \brief Maximum/Minimum grad fusion pass (5 -> 2), for Ascend950 series.
 *
 *        TF decomposed maximum/minimum gradient subgraph (see math_grad.py
 *        _MaximumMinimumGrad, selector is greater_equal/less_equal). Three
 *        forms are generated by TF autodiff depending on var_list:
 *
 *          both:    x1 -+-> GE/LE --+-> Select_dx(cmp, dz, zeros) --> [Sum] --> dx
 *                   x2 -+           +-> Select_dy(cmp, zeros, dz) --> [Sum] --> dy
 *          dx-only: x1 -+-> GE/LE -----> Select_dx(cmp, dz, zeros) --> [Sum] --> dx
 *          dy-only: x1 -+-> GE/LE -----> Select_dy(cmp, zeros, dz) --> [Sum] --> dy
 *          dz / zeros(Const, all zero) feed the Selects as shown.
 *
 *        Fused result (Sum/Reshape are NOT absorbed, they stay outside the
 *        pattern boundary and are re-linked to the fused node outputs):
 *
 *          both:    MaximumGrad/MinimumGrad(grads=dz, x1, x2, grad_x=true,  grad_y=true)
 *          dx-only: MaximumGrad/MinimumGrad(grads=dz, x1, x2, grad_x=true,  grad_y=false), y2 unused
 *          dy-only: MaximumGrad/MinimumGrad(grads=dz, x1, x2, grad_x=false, grad_y=true),  y1 unused
 *
 *        Equivalence: Select_dx(cmp, dz, 0) == dz * (cmp == true), Select_dy
 *        is its complement, which is exactly the broadcast-output mask
 *        semantics of the Ascend950 MaximumGrad/MinimumGrad implementation.
 *
 *        Single-form patterns never falsely match a both-form subgraph: the
 *        matcher requires the subgraph to be self-contained (documented in
 *        subgraph_boundary.h), so a cmp whose output also feeds an outside
 *        Select is rejected for the single-form pattern.
 */

