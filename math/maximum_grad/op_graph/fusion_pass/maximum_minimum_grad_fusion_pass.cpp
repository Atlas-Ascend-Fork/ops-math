const std::string kPassName = "MaximumMinimumGradFusionPass";
const int64_t kCaptureIdxCmp = 0;
const size_t kPatternInputNum = 4UL; // 0: dz(grads), 1: x1, 2: x2, 3: zeros
const size_t kInputIdxGrads = 0UL;
const size_t kInputIdxX1 = 1UL;
const size_t kInputIdxX2 = 2UL;
const size_t kInputIdxZeros = 3UL;
const char* const kCmpGreaterEqual = "GreaterEqual";
const char* const kCmpLessEqual = "LessEqual";
const char* const kOpMaximumGrad = "MaximumGrad";
const char* const kOpMinimumGrad = "MinimumGrad";
const char* const kScopeMaximumGrad = "Maximum_grad";
const char* const kScopeMinimumGrad = "Minimum_grad";
const char* const kConstOpType = "Const";
// The TF adapter converts TF "Const" nodes to GE type "Constant", while the
// ES graph builder used by the UT produces "Const". Both must be accepted.
const char* const kGeConstantOpType = "Constant";
const char* const kSelectOpType = "Select";
const char* const kSelectV2OpType = "SelectV2";
