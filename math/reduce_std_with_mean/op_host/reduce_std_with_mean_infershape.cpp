static ge::graphStatus HandleScalarInput(gert::InferShapeContext* context, const gert::Shape* xShape,
                                         gert::Shape* yShape)
{
    if (xShape->GetDimNum() != 0) {
        return GRAPH_SUCCESS;
    }
    auto attrs = context->GetAttrs();
    if (attrs == nullptr) {
        OP_LOGE_WITH_INVALID_INPUT(context->GetNodeName(), "attrs");
        return ge::GRAPH_FAILED;
    }
    const bool keepDim = ReadKeepDim(attrs);
    if (keepDim) {
        *yShape = gert::Shape({1});
    } else {
        *yShape = gert::Shape();
    }
    OP_LOGD(context->GetNodeName(), "scalar input: keepDim=%d, yShape dims=%zu", static_cast<int>(keepDim),
            yShape->GetDimNum());
    return GRAPH_SUCCESS;
}

