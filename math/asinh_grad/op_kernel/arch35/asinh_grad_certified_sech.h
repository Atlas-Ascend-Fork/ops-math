            Reg::MulAddDst(residual, negativeQuotient, coshLow, correctionMask);
            Reg::Div<float, &REG_DIV_CONFIG>(correction, residual, coshReg, correctionMask);
            Reg::Add(correction, result, correction, correctionMask);
